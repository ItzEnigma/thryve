// main.c — Example C application using Thryve FFI library
//
// This example demonstrates how to create a plugin and observer using the
// Thryve FFI layer from C. The plugin's entry point wires a pipeline of typed
// tasks: Hash, then LoadImg, then Thumbnail and Metadata sharing the decoded
// image, joined into Report.
//
// Build with CMake or manually:
//   gcc -std=c11 -I<OUT_DIR> main.c -L<LIB_DIR> -lthryve_ffi -o thryve_example
//
// <OUT_DIR> is the directory containing thryve.h (generated by cbindgen)
// <LIB_DIR> is the directory containing thryve_ffi.dll (Windows) or libthryve_ffi.so (Linux)

#include "thryve.h"  // C-compatible header (generated by cbindgen)

#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

// The engine's packet handle, for the plugin's entry point to send tasks with.
static ThryvePacketHandle g_packet_handle = NULL;

// ============================================================================
// Typed Tasks: Hash, then LoadImg, then Thumbnail and Metadata, joined into Report
// ============================================================================

typedef struct {
    int width;
    int height;
    unsigned char* pixels;
} Image;

static void free_image(void* image) {
    Image* img = image;
    free(img->pixels);
    free(img);
}

// Passes the error a task was handed on, as the task's own.
static ThryveOutcome pass_error_on(ThryveHandoff handoff) {
    return thryve_outcome_error(thryve_handoff_error_code(handoff),
                                thryve_handoff_error_message(handoff));
}

// Hash: the file's digest, as the task's value. Thryve frees it with `free`
// once nobody can take it any more.
static ThryveOutcome hash_file(void* user_data) {
    const char* path = user_data;
    uint64_t* digest = malloc(sizeof *digest);
    if (digest == NULL) {
        return thryve_outcome_error(1, "out of memory");
    }

    *digest = 14695981039346656037ULL;
    for (const char* c = path; *c != '\0'; c++) {
        *digest = (*digest ^ (unsigned char)*c) * 1099511628211ULL;
    }
    printf("Hash: %s\n", path);
    return thryve_outcome_value(digest, free);
}

// LoadImg: decodes the image whose digest it was handed. Hash's error, if any,
// is passed on.
static ThryveOutcome load_img(ThryveHandoff digest, void* user_data) {
    (void)user_data;
    if (thryve_handoff_is_error(digest)) {
        return pass_error_on(digest);
    }

    const uint64_t* hash = thryve_handoff_value(digest, 0);
    Image* image = malloc(sizeof *image);
    if (image == NULL) {
        return thryve_outcome_error(1, "out of memory");
    }
    image->width = 640;
    image->height = 480;
    image->pixels = calloc((size_t)image->width * (size_t)image->height, 1);
    if (image->pixels == NULL) {
        free(image);
        return thryve_outcome_error(1, "out of memory");
    }

    printf("LoadImg: decoded image %016llx\n", (unsigned long long)*hash);
    return thryve_outcome_value(image, free_image);
}

// Thumbnail and Metadata are fan-out followers: they read the one decoded image
// in place, at the same time, so they must not change it. Each returns a number
// carried in the pointer itself, so there's nothing to free.
static ThryveOutcome thumbnail(ThryveHandoff image, void* user_data) {
    (void)user_data;
    if (thryve_handoff_is_error(image)) {
        return pass_error_on(image);
    }

    const Image* img = thryve_handoff_value(image, 0);
    return thryve_outcome_value((void*)(uintptr_t)(img->width / 8), NULL);
}

static ThryveOutcome metadata(ThryveHandoff image, void* user_data) {
    (void)user_data;
    if (thryve_handoff_is_error(image)) {
        return pass_error_on(image);
    }

    const Image* img = thryve_handoff_value(image, 0);
    return thryve_outcome_value((void*)(uintptr_t)(img->width * img->height), NULL);
}

// Report joins Thumbnail and Metadata: it runs once both are done, with their
// values in the order they were joined, or with the first error.
static ThryveOutcome report(ThryveHandoff parts, void* user_data) {
    (void)user_data;
    if (thryve_handoff_is_error(parts)) {
        fprintf(stderr, "Report: part %zu failed: %s\n",
                thryve_handoff_error_position(parts),
                thryve_handoff_error_message(parts));
        return pass_error_on(parts);
    }

    uintptr_t thumbnail_width = (uintptr_t)thryve_handoff_value(parts, 0);
    uintptr_t pixel_count = (uintptr_t)thryve_handoff_value(parts, 1);
    printf("Report: thumbnail %zu pixels wide, image of %zu pixels\n",
           (size_t)thumbnail_width, (size_t)pixel_count);
    return thryve_outcome_value(NULL, NULL);
}

// Declares the whole pipeline. Each call uses up the handle it's given, so no
// handle is used twice, and a failed call frees what it was given.
static void start_photo_pipeline(const char* path) {
    // Hash's user data is the path: a string literal, so nothing to free.
    ThryveAdvTask hash = thryve_adv_task_create("Hash", 2, hash_file, (void*)path, NULL);
    ThryveAdvHandle digest = thryve_packet_handle_send_adv_task(g_packet_handle, hash);
    if (digest == NULL) {
        fprintf(stderr, "Failed to send Hash: %s\n", thryve_last_error());
        return;
    }

    ThryveAdvHandle image = thryve_adv_handle_then(digest, "LoadImg", load_img, NULL, NULL);

    ThryveFanoutGroup group = thryve_adv_handle_fan_out(image);
    ThryveAdvHandle parts[2];
    parts[0] = thryve_fanout_then(group, "Thumbnail", thumbnail, NULL, NULL);
    parts[1] = thryve_fanout_then(group, "Metadata", metadata, NULL, NULL);
    if (thryve_fanout_send(group) != ThryveStatus_Ok) {
        fprintf(stderr, "Failed to send the fan-out: %s\n", thryve_last_error());
    }

    ThryveAdvHandle report_handle = thryve_adv_handles_join(parts, 2, "Report", report, NULL, NULL);
    if (report_handle == NULL) {
        fprintf(stderr, "Failed to declare Report: %s\n", thryve_last_error());
        return;
    }

    // Nothing follows Report: let its handle go.
    thryve_adv_handle_free(report_handle);
}

// ============================================================================
// Plugin Implementation
// ============================================================================

// Plugin cleanup function — called once when the engine shuts down.
// Returns ThryveStatus_Ok if it worked; any other value is logged to Error.log.
int my_plugin_cleanup(const void* core_ptr) {
    (void)core_ptr;
    printf("Plugin cleanup called\n");
    return ThryveStatus_Ok;
}

// Plugin entry point — called once the engine is up, on one of its workers, with
// the plugin's core pointer. It fills in the result it's given, which starts
// empty: left alone, it reports nothing.
void my_plugin_entry_point(ThryveTaskResult* result, void* core_ptr) {
    (void)core_ptr;
    printf("Plugin entry point called\n");
    start_photo_pipeline("photo.png");

    // Report that the plugin started, in Main.log. Setting the fields one by
    // one works too: result->result_type = "Started"; and so on.
    *result = thryve_task_result_new("Started", "Plugin started", "Main");
}

// ============================================================================
// Observer Implementation
// ============================================================================

// Observer cleanup function — called once when the engine shuts down.
void my_observer_cleanup(const void* core_ptr) {
    (void)core_ptr;
    printf("Observer cleanup called\n");
}

// Observer job — the observer's whole loop, run once on its own thread. It
// waits for each notification sent to the observer, until the engine shuts the
// observer down. The observer belongs to the engine: don't free it.
void my_observer_job(ThryveObserver observer) {
    printf("Observer job started\n");

    ThryveNotif notif;
    while ((notif = thryve_observer_pop(observer)) != NULL) {
        printf("Observer got a notification\n");
        thryve_notification_free(notif);
    }

    printf("Observer job stopped\n");
}

// ============================================================================
// Task Job Implementation
// ============================================================================

// A task's job: it has nothing to report, so it leaves its result alone.
void my_task_job(ThryveTaskResult* result, void* user_data) {
    (void)result;
    (void)user_data;
    printf("Task job called\n");
}

// Shutdown task job — a "Fin" result_type is what tells the engine to finalize
// and set its exit flag. There is no separate "stop" FFI call; submitting a
// task like this is the only way to make the engine loop exit, which in turn
// is what lets thryve_run_interactive_free's join() return.
void shutdown_task_job(ThryveTaskResult* result, void* user_data) {
    (void)user_data;
    printf("Shutdown task job called\n");
    *result = thryve_task_result_new("Fin", "Shutting down", "Main");
}

// ============================================================================
// Main Function
// ============================================================================

int main(void) {
    printf("=== Thryve FFI Example ===\n");

    // 1. Create configuration
    ThryveConfig config = thryve_config_default();
    if (!config) {
        fprintf(stderr, "Failed to create config: %s\n", thryve_last_error());
        return 1;
    }
    printf("Config created\n");

    // 2. Create context from configuration
    ThryveCtx ctx = thryve_ctx_create(config);
    if (!ctx) {
        fprintf(stderr, "Failed to create context: %s\n", thryve_last_error());
        thryve_config_free(config);
        return 1;
    }
    printf("Context created\n");

    // 3. Get the engine's connected packet handle from ctx.
    // Do NOT use a standalone packet handle here — it would not be wired to
    // this ctx's engine, and any task/notification sent through it would be
    // silently dropped once the engine starts running.
    ThryvePacketHandle packet_handle = thryve_ctx_get_packet_handle(ctx);
    if (!packet_handle) {
        fprintf(stderr, "Failed to get packet handle: %s\n", thryve_last_error());
        thryve_ctx_free(ctx);
        thryve_config_free(config);
        return 1;
    }
    g_packet_handle = packet_handle;
    printf("PacketHandle created\n");

    // 4. Create a plugin
    ThryvePlugin plugin = thryve_plugin_create(
        "MyType",             // type
        NULL,                 // plg_core_ptr (opaque pointer)
        packet_handle,        // tx (packet handle - REQUIRED)
        my_plugin_cleanup,    // clean_up callback
        my_plugin_entry_point // entry_point callback
    );

    if (!plugin) {
        fprintf(stderr, "Failed to create plugin: %s\n", thryve_last_error());
        thryve_packet_handle_free(packet_handle);
        thryve_ctx_free(ctx);
        thryve_config_free(config);
        return 1;
    }
    printf("Plugin created\n");

    // 5. Add plugin to context (takes ownership of the plugin)
    ThryveStatus status = thryve_ctx_add_plugin(ctx, plugin);
    if (status != ThryveStatus_Ok) {
        fprintf(stderr, "Failed to add plugin to context: %s\n", thryve_last_error());
        thryve_plugin_free(plugin);
        thryve_packet_handle_free(packet_handle);
        thryve_ctx_free(ctx);
        thryve_config_free(config);
        return 1;
    }
    printf("Plugin added to context\n");

    // 6. Create an observer
    ThryveObserver observer = thryve_observer_create(
        "MyType",             // type
        NULL,                 // obs_core_ptr (opaque pointer)
        packet_handle,        // tx (packet handle - REQUIRED)
        my_observer_cleanup,  // clean_up callback
        my_observer_job       // obs_job callback
    );

    if (!observer) {
        fprintf(stderr, "Failed to create observer: %s\n", thryve_last_error());
    } else {
        printf("Observer created\n");

        // Add observer to context (takes ownership of the observer)
        status = thryve_ctx_add_observer(ctx, observer);
        if (status != ThryveStatus_Ok) {
            fprintf(stderr, "Failed to add observer to context: %s\n", thryve_last_error());
            thryve_observer_free(observer);
        } else {
            printf("Observer added to context\n");
        }
    }

    // 7. Create a task
    ThryveTask task = thryve_task_create(
        "MyTask",             // name
        0,                    // priority
        my_task_job,          // job callback
        NULL,                 // user data, passed to the job
        NULL                  // frees the user data (NULL: nothing to free)
    );

    if (!task) {
        fprintf(stderr, "Failed to create task: %s\n", thryve_last_error());
    } else {
        printf("Task created\n");

        // Send the task to the context. thryve_ctx_send_task takes ownership of
        // task — do NOT call thryve_task_free on it afterward, that would be a
        // double-free.
        status = thryve_ctx_send_task(ctx, task);
        if (status != ThryveStatus_Ok) {
            fprintf(stderr, "Failed to send task: %s\n", thryve_last_error());
        } else {
            printf("Task sent to context\n");
        }
    }

    // 8. Start the engine (interactive mode). This consumes ctx — after this
    // call, ctx is no longer valid and must never be freed or otherwise used
    // (not even on the error path below). packet_handle remains our only way
    // to feed the now-running engine.
    printf("\nStarting interactive engine...\n");
    printf("Press Enter to stop...\n");

    ThryveRunHandle handle = thryve_run_interactive_start(ctx);
    if (handle) {
        // Wait for user input to stop
        getchar();

        // Submit a shutdown task so the engine actually finalizes and exits
        // its loop. Without this, thryve_run_interactive_free would block
        // forever waiting for a thread that never stops running.
        ThryveTask shutdown_task = thryve_task_create("Shutdown", 0, shutdown_task_job, NULL, NULL);
        if (shutdown_task) {
            thryve_packet_handle_send_task(packet_handle, shutdown_task);
        }

        // Now safe to call — blocks only until the engine thread, having
        // processed the shutdown task, returns.
        thryve_run_interactive_free(handle);
    } else {
        fprintf(stderr, "Failed to start the engine: %s\n", thryve_last_error());
    }

    // 9. Cleanup
    // Note: plugin and observer are owned by ctx, so don't free them.
    // ctx itself was already consumed by thryve_run_interactive_start above —
    // do NOT call thryve_ctx_free(ctx) here, that would be a double-free.
    thryve_packet_handle_free(packet_handle);
    thryve_config_free(config);

    printf("\n=== Example finished ===\n");
    return 0;
}
