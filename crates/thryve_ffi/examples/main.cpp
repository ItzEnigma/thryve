// main.cpp — Example C++ application using Thryve FFI library
//
// This example demonstrates how to create a plugin and observer
// using the Thryve FFI layer from C++.
//
// Build with CMake or manually:
//   g++ -std=c++17 -I<OUT_DIR> main.cpp -L<LIB_DIR> -lthryve_ffi -o thryve_example
//
// <OUT_DIR> is the directory containing thryve_ffi.h (generated by build.rs)
// <LIB_DIR> is the directory containing thryve_ffi.dll (Windows) or libthryve_ffi.so (Linux)

#include "thryve_ffi.h"  // C++ wrapper with extern "C" (generated by build.rs)
#include <iostream>
#include <cstring>

// ============================================================================
// Plugin Implementation
// ============================================================================

// Plugin cleanup function — called when the plugin is being freed
extern "C" void my_plugin_cleanup(const void* core_ptr) {
    std::cout << "Plugin cleanup called" << std::endl;
}

// Plugin entry point — called when the plugin's task is executed
extern "C" ThryveTaskResult my_plugin_entry_point(void) {
    std::cout << "Plugin entry point called" << std::endl;

    ThryveTaskResult result = {0};  // has_chain = 0, chain_task = NULL
    // Execute plugin logic here
    return result;
}

// ============================================================================
// Observer Implementation
// ============================================================================

// Observer cleanup function — called when the observer is being freed
extern "C" void my_observer_cleanup(const void* core_ptr) {
    std::cout << "Observer cleanup called" << std::endl;
}

// Observer job function — called when the observer runs
extern "C" void my_observer_job(ThryveObserver observer) {
    std::cout << "Observer job called" << std::endl;

    // IMPORTANT: The observer parameter is an Arc<Observer> clone.
    // You must drop it when done to prevent memory leaks.
    // Use the FFI free function or manually drop the Arc.
    thryve_observer_free(observer);
}

// ============================================================================
// Task Job Implementation
// ============================================================================

extern "C" ThryveTaskResult my_task_job(void) {
    std::cout << "Task job called" << std::endl;

    ThryveTaskResult result = {0};
    return result;
}

// Shutdown task job — returning a "Fin" result_type is what tells the engine
// to finalize and set its exit flag. There is no separate "stop" FFI call;
// submitting a task like this is the only way to make the engine loop exit,
// which in turn is what lets thryve_run_interactive_free's join() return.
extern "C" ThryveTaskResult shutdown_task_job(void) {
    std::cout << "Shutdown task job called" << std::endl;
    return thryve_task_result_new("Fin", "Shutting down", "Main");
}

// ============================================================================
// Main Function
// ============================================================================

int main() {
    std::cout << "=== Thryve FFI Example ===" << std::endl;

    // 1. Create configuration
    ThryveConfig config = thryve_config_default();
    if (!config) {
        std::cerr << "Failed to create config" << std::endl;
        return 1;
    }
    std::cout << "Config created" << std::endl;

    // 2. Create context from configuration
    ThryveCtx ctx = thryve_ctx_create(config);
    if (!ctx) {
        std::cerr << "Failed to create context" << std::endl;
        thryve_config_free(config);
        return 1;
    }
    std::cout << "Context created" << std::endl;

    // 3. Get the engine's connected packet handle from ctx.
    // Do NOT use a standalone packet handle here — it would not be wired to
    // this ctx's engine, and any task/notification sent through it would be
    // silently dropped once the engine starts running.
    ThryvePacketHandle packet_handle = thryve_ctx_get_packet_handle(ctx);
    if (!packet_handle) {
        std::cerr << "Failed to get packet handle" << std::endl;
        thryve_ctx_free(ctx);
        thryve_config_free(config);
        return 1;
    }
    std::cout << "PacketHandle created" << std::endl;

    // 4. Create a plugin
    ThryvePlugin plugin = thryve_plugin_create(
        "MyType",             // type
        nullptr,              // plg_core_ptr (opaque pointer)
        packet_handle,        // tx (packet handle - REQUIRED)
        my_plugin_cleanup,    // clean_up callback
        my_plugin_entry_point // entry_point callback
    );

    if (!plugin) {
        std::cerr << "Failed to create plugin" << std::endl;
        thryve_packet_handle_free(packet_handle);
        thryve_ctx_free(ctx);
        thryve_config_free(config);
        return 1;
    }
    std::cout << "Plugin created" << std::endl;

    // 5. Add plugin to context (takes ownership of the plugin)
    ThryveStatus status = thryve_ctx_add_plugin(ctx, plugin);
    if (status != ThryveStatus_Ok) {
        std::cerr << "Failed to add plugin to context: " << status << std::endl;
        thryve_plugin_free(plugin);
        thryve_packet_handle_free(packet_handle);
        thryve_ctx_free(ctx);
        thryve_config_free(config);
        return 1;
    }
    std::cout << "Plugin added to context" << std::endl;

    // 6. Create an observer
    ThryveObserver observer = thryve_observer_create(
        "MyType",             // type
        nullptr,              // obs_core_ptr (opaque pointer)
        packet_handle,        // tx (packet handle - REQUIRED)
        my_observer_cleanup,  // clean_up callback
        my_observer_job       // obs_job callback
    );

    if (!observer) {
        std::cerr << "Failed to create observer" << std::endl;
    } else {
        std::cout << "Observer created" << std::endl;

        // Add observer to context
        status = thryve_ctx_add_observer(ctx, observer);
        if (status != ThryveStatus_Ok) {
            std::cerr << "Failed to add observer to context: " << status << std::endl;
        } else {
            std::cout << "Observer added to context" << std::endl;
        }
    }

    // 7. Create a task
    ThryveTask task = thryve_task_create(
        "MyTask",             // name
        0,                    // priority
        my_task_job           // job callback
    );

    if (!task) {
        std::cerr << "Failed to create task" << std::endl;
    } else {
        std::cout << "Task created" << std::endl;

        // Send the task to the context. thryve_ctx_send_task takes ownership of
        // task — do NOT call thryve_task_free on it afterward, that would be a
        // double-free.
        status = thryve_ctx_send_task(ctx, task);
        if (status != ThryveStatus_Ok) {
            std::cerr << "Failed to send task: " << status << std::endl;
        } else {
            std::cout << "Task sent to context" << std::endl;
        }
    }

    // 8. Start the engine (interactive mode). This consumes ctx — after this
    // call, ctx is no longer valid and must never be freed or otherwise used.
    // packet_handle remains our only way to feed the now-running engine.
    std::cout << "\nStarting interactive engine..." << std::endl;
    std::cout << "Press Enter to stop..." << std::endl;

    ThryveRunHandle handle = thryve_run_interactive_start(ctx);
    if (handle) {
        // Wait for user input to stop
        std::cin.get();

        // Submit a shutdown task so the engine actually finalizes and exits
        // its loop. Without this, thryve_run_interactive_free would block
        // forever waiting for a thread that never stops running.
        ThryveTask shutdown_task = thryve_task_create("Shutdown", 0, shutdown_task_job);
        if (shutdown_task) {
            thryve_packet_handle_send_task(packet_handle, shutdown_task);
        }

        // Now safe to call — blocks only until the engine thread, having
        // processed the shutdown task, returns.
        thryve_run_interactive_free(handle);
    }

    // 9. Cleanup
    // Note: plugin and observer are owned by ctx, so don't free them.
    // ctx itself was already consumed by thryve_run_interactive_start above —
    // do NOT call thryve_ctx_free(ctx) here, that would be a double-free.
    thryve_packet_handle_free(packet_handle);
    thryve_config_free(config);

    std::cout << "\n=== Example finished ===" << std::endl;
    return 0;
}
