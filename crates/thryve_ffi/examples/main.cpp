// main.cpp — Example C++ application using Thryve FFI library
//
// This example demonstrates how to create a plugin and observer using the
// Thryve FFI layer from C++. The plugin's entry point wires a pipeline of
// typed tasks: Hash, then LoadImg, then Thumbnail and Metadata sharing the
// decoded image, joined into Report.
//
// Build with CMake or manually:
//   g++ -std=c++17 -I<OUT_DIR> main.cpp -L<LIB_DIR> -lthryve_ffi -o thryve_example
//
// <OUT_DIR> is the directory containing thryve_ffi.h (generated by build.rs)
// <LIB_DIR> is the directory containing thryve_ffi.dll (Windows) or libthryve_ffi.so (Linux)

#include "thryve_ffi.h"  // C++ wrapper with extern "C" (generated by build.rs)
#include <cstdint>
#include <iostream>
#include <string>
#include <vector>

// The engine's packet handle, for the plugin's entry point to send tasks with.
static ThryvePacketHandle g_packet_handle = nullptr;

// ============================================================================
// Typed Tasks: Hash, then LoadImg, then Thumbnail and Metadata, joined into Report
// ============================================================================

struct Image {
    int width;
    int height;
    std::vector<unsigned char> pixels;
};

// Passes the error a task was handed on, as the task's own.
static ThryveOutcome pass_error_on(ThryveHandoff handoff) {
    return thryve_outcome_error(thryve_handoff_error_code(handoff),
                                thryve_handoff_error_message(handoff));
}

// Declares the whole pipeline. Each call uses up the handle it's given, so no
// handle is used twice, and a failed call frees what it was given.
//
// The jobs are lambdas that capture nothing, so each converts to the C
// function pointer Thryve calls. Values are `new`ed, and Thryve frees them
// with the matching `delete` once nobody can take them any more.
static void start_photo_pipeline(const char* path) {
    // Hash: the file's digest, as the task's value. Its user data is the path,
    // a std::string that Thryve deletes once Hash has run.
    ThryveAdvTask hash = thryve_adv_task_create(
        "Hash", 2,
        [](void* user_data) -> ThryveOutcome {
            const std::string& path = *static_cast<std::string*>(user_data);
            auto* digest = new std::uint64_t(std::hash<std::string>{}(path));
            std::cout << "Hash: " << path << std::endl;
            return thryve_outcome_value(digest, [](void* value) {
                delete static_cast<std::uint64_t*>(value);
            });
        },
        new std::string(path),
        [](void* user_data) { delete static_cast<std::string*>(user_data); });

    ThryveAdvHandle digest = thryve_packet_handle_send_adv_task(g_packet_handle, hash);
    if (digest == nullptr) {
        std::cerr << "Failed to send Hash: " << thryve_last_error() << std::endl;
        return;
    }

    // LoadImg: decodes the image whose digest it was handed. Hash's error, if
    // any, is passed on.
    ThryveAdvHandle image = thryve_adv_handle_then(
        digest, "LoadImg",
        [](ThryveHandoff digest, void*) -> ThryveOutcome {
            if (thryve_handoff_is_error(digest)) {
                return pass_error_on(digest);
            }

            auto hash = *static_cast<const std::uint64_t*>(thryve_handoff_value(digest, 0));
            auto* image = new Image{640, 480, std::vector<unsigned char>(640 * 480)};
            std::cout << "LoadImg: decoded image " << std::hex << hash << std::dec << std::endl;
            return thryve_outcome_value(image, [](void* value) {
                delete static_cast<Image*>(value);
            });
        },
        nullptr, nullptr);

    // Thumbnail and Metadata are fan-out followers: they read the one decoded
    // image in place, at the same time, so they must not change it. Each
    // returns a number carried in the pointer itself, so there's nothing to free.
    ThryveFanoutGroup group = thryve_adv_handle_fan_out(image);
    ThryveAdvHandle parts[2];
    parts[0] = thryve_fanout_then(
        group, "Thumbnail",
        [](ThryveHandoff image, void*) -> ThryveOutcome {
            if (thryve_handoff_is_error(image)) {
                return pass_error_on(image);
            }
            const auto* img = static_cast<const Image*>(thryve_handoff_value(image, 0));
            return thryve_outcome_value(reinterpret_cast<void*>(std::uintptr_t(img->width / 8)),
                                        nullptr);
        },
        nullptr, nullptr);
    parts[1] = thryve_fanout_then(
        group, "Metadata",
        [](ThryveHandoff image, void*) -> ThryveOutcome {
            if (thryve_handoff_is_error(image)) {
                return pass_error_on(image);
            }
            const auto* img = static_cast<const Image*>(thryve_handoff_value(image, 0));
            return thryve_outcome_value(
                reinterpret_cast<void*>(std::uintptr_t(img->width * img->height)), nullptr);
        },
        nullptr, nullptr);
    if (thryve_fanout_send(group) != ThryveStatus_Ok) {
        std::cerr << "Failed to send the fan-out: " << thryve_last_error() << std::endl;
    }

    // Report joins Thumbnail and Metadata: it runs once both are done, with
    // their values in the order they were joined, or with the first error.
    ThryveAdvHandle report = thryve_adv_handles_join(
        parts, 2, "Report",
        [](ThryveHandoff parts, void*) -> ThryveOutcome {
            if (thryve_handoff_is_error(parts)) {
                std::cerr << "Report: part " << thryve_handoff_error_position(parts)
                          << " failed: " << thryve_handoff_error_message(parts) << std::endl;
                return pass_error_on(parts);
            }

            auto thumbnail_width = reinterpret_cast<std::uintptr_t>(thryve_handoff_value(parts, 0));
            auto pixel_count = reinterpret_cast<std::uintptr_t>(thryve_handoff_value(parts, 1));
            std::cout << "Report: thumbnail " << thumbnail_width << " pixels wide, image of "
                      << pixel_count << " pixels" << std::endl;
            return thryve_outcome_value(nullptr, nullptr);
        },
        nullptr, nullptr);
    if (report == nullptr) {
        std::cerr << "Failed to declare Report: " << thryve_last_error() << std::endl;
        return;
    }

    // Nothing follows Report: let its handle go.
    thryve_adv_handle_free(report);
}

// ============================================================================
// Plugin Implementation
// ============================================================================

// Plugin cleanup function — called once when the engine shuts down.
// Returns ThryveStatus_Ok if it worked; any other value is logged to Error.log.
extern "C" int my_plugin_cleanup(const void*) {
    std::cout << "Plugin cleanup called" << std::endl;
    return ThryveStatus_Ok;
}

// Plugin entry point — called once the engine is up, on one of its workers, with
// the plugin's core pointer. It fills in the result it's given, which starts
// empty: left alone, it reports nothing.
extern "C" void my_plugin_entry_point(ThryveTaskResult* result, void*) {
    std::cout << "Plugin entry point called" << std::endl;
    start_photo_pipeline("photo.png");

    // Report that the plugin started, in Main.log.
    *result = thryve_task_result_new("Started", "Plugin started", "Main");
}

// ============================================================================
// Observer Implementation
// ============================================================================

// Observer cleanup function — called once when the engine shuts down.
extern "C" void my_observer_cleanup(const void*) {
    std::cout << "Observer cleanup called" << std::endl;
}

// Observer job — the observer's whole loop, run once on its own thread. It
// waits for each notification sent to the observer, until the engine shuts the
// observer down. The observer belongs to the engine: don't free it.
extern "C" void my_observer_job(ThryveObserver observer) {
    std::cout << "Observer job started" << std::endl;

    while (ThryveNotif notif = thryve_observer_pop(observer)) {
        std::cout << "Observer got a notification" << std::endl;
        thryve_notification_free(notif);
    }

    std::cout << "Observer job stopped" << std::endl;
}

// ============================================================================
// Task Job Implementation
// ============================================================================

// A task's job: it has nothing to report, so it leaves its result alone.
extern "C" void my_task_job(ThryveTaskResult*, void*) {
    std::cout << "Task job called" << std::endl;
}

// Shutdown task job — a "Fin" result_type is what tells the engine to finalize
// and set its exit flag. There is no separate "stop" FFI call; submitting a
// task like this is the only way to make the engine loop exit, which in turn
// is what lets thryve_run_interactive_free's join() return.
extern "C" void shutdown_task_job(ThryveTaskResult* result, void*) {
    std::cout << "Shutdown task job called" << std::endl;
    *result = thryve_task_result_new("Fin", "Shutting down", "Main");
}

// ============================================================================
// Main Function
// ============================================================================

int main() {
    std::cout << "=== Thryve FFI Example ===" << std::endl;

    // 1. Create configuration
    ThryveConfig config = thryve_config_default();
    if (!config) {
        std::cerr << "Failed to create config: " << thryve_last_error() << std::endl;
        return 1;
    }
    std::cout << "Config created" << std::endl;

    // 2. Create context from configuration
    ThryveCtx ctx = thryve_ctx_create(config);
    if (!ctx) {
        std::cerr << "Failed to create context: " << thryve_last_error() << std::endl;
        thryve_config_free(config);
        return 1;
    }
    std::cout << "Context created" << std::endl;

    // 3. Get the engine's connected packet handle from ctx.
    // Do NOT use a standalone packet handle here — it would not be wired to
    // this ctx's engine, and any task/notification sent through it would be
    // silently dropped once the engine starts running.
    ThryvePacketHandle packet_handle = thryve_ctx_get_packet_handle(ctx);
    if (!packet_handle) {
        std::cerr << "Failed to get packet handle: " << thryve_last_error() << std::endl;
        thryve_ctx_free(ctx);
        thryve_config_free(config);
        return 1;
    }
    g_packet_handle = packet_handle;
    std::cout << "PacketHandle created" << std::endl;

    // 4. Create a plugin
    ThryvePlugin plugin = thryve_plugin_create(
        "MyType",             // type
        nullptr,              // plg_core_ptr (opaque pointer)
        packet_handle,        // tx (packet handle - REQUIRED)
        my_plugin_cleanup,    // clean_up callback
        my_plugin_entry_point // entry_point callback
    );

    if (!plugin) {
        std::cerr << "Failed to create plugin: " << thryve_last_error() << std::endl;
        thryve_packet_handle_free(packet_handle);
        thryve_ctx_free(ctx);
        thryve_config_free(config);
        return 1;
    }
    std::cout << "Plugin created" << std::endl;

    // 5. Add plugin to context (takes ownership of the plugin)
    ThryveStatus status = thryve_ctx_add_plugin(ctx, plugin);
    if (status != ThryveStatus_Ok) {
        std::cerr << "Failed to add plugin to context: " << thryve_last_error() << std::endl;
        thryve_plugin_free(plugin);
        thryve_packet_handle_free(packet_handle);
        thryve_ctx_free(ctx);
        thryve_config_free(config);
        return 1;
    }
    std::cout << "Plugin added to context" << std::endl;

    // 6. Create an observer
    ThryveObserver observer = thryve_observer_create(
        "MyType",             // type
        nullptr,              // obs_core_ptr (opaque pointer)
        packet_handle,        // tx (packet handle - REQUIRED)
        my_observer_cleanup,  // clean_up callback
        my_observer_job       // obs_job callback
    );

    if (!observer) {
        std::cerr << "Failed to create observer: " << thryve_last_error() << std::endl;
    } else {
        std::cout << "Observer created" << std::endl;

        // Add observer to context (takes ownership of the observer)
        status = thryve_ctx_add_observer(ctx, observer);
        if (status != ThryveStatus_Ok) {
            std::cerr << "Failed to add observer to context: " << thryve_last_error()
                      << std::endl;
            thryve_observer_free(observer);
        } else {
            std::cout << "Observer added to context" << std::endl;
        }
    }

    // 7. Start the engine (interactive mode). This consumes ctx — after this
    // call, ctx is no longer valid and must never be freed or otherwise used.
    // packet_handle remains our only way to feed the now-running engine.
    std::cout << "\nStarting interactive engine..." << std::endl;

    ThryveRunHandle handle = thryve_run_interactive_start(ctx);
    if (handle) {
        // 8. Send a task. Sends work only once the engine is started: before
        // thryve_run_interactive_start, packet_handle refuses them with
        // ThryveStatus_InvalidState.
        ThryveTask task = thryve_task_create(
            "MyTask",             // name
            0,                    // priority
            my_task_job,          // job callback
            nullptr,              // user data, passed to the job
            nullptr               // frees the user data (NULL: nothing to free)
        );

        if (!task) {
            std::cerr << "Failed to create task: " << thryve_last_error() << std::endl;
        } else {
            std::cout << "Task created" << std::endl;

            // thryve_packet_handle_send_task takes ownership of task, even when
            // it fails — do NOT call thryve_task_free on it afterward, that
            // would be a double-free.
            status = thryve_packet_handle_send_task(packet_handle, task);
            if (status != ThryveStatus_Ok) {
                std::cerr << "Failed to send task: " << thryve_last_error() << std::endl;
            } else {
                std::cout << "Task sent to the engine" << std::endl;
            }
        }

        // Wait for user input to stop
        std::cout << "Press Enter to stop..." << std::endl;
        std::cin.get();

        // Submit a shutdown task so the engine actually finalizes and exits
        // its loop. Without this, thryve_run_interactive_free would block
        // forever waiting for a thread that never stops running.
        ThryveTask shutdown_task = thryve_task_create("Shutdown", 0, shutdown_task_job, nullptr, nullptr);
        if (shutdown_task) {
            thryve_packet_handle_send_task(packet_handle, shutdown_task);
        }

        // Now safe to call — blocks only until the engine thread, having
        // processed the shutdown task, returns.
        thryve_run_interactive_free(handle);
    } else {
        std::cerr << "Failed to start the engine: " << thryve_last_error() << std::endl;
    }

    // 9. Cleanup
    // Note: plugin and observer are owned by ctx, so don't free them.
    // ctx itself was already consumed by thryve_run_interactive_start above —
    // do NOT call thryve_ctx_free(ctx) here, that would be a double-free.
    thryve_packet_handle_free(packet_handle);
    thryve_config_free(config);

    std::cout << "\n=== Example finished ===" << std::endl;
    return 0;
}
