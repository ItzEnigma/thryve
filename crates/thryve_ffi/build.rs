//! Build script that generates the C header file using cbindgen.
//!
//! This ensures the header file is always in sync with the Rust FFI definitions.
//! The header is generated during the build process and placed in OUT_DIR.
//!
//! The build script also creates a C++ wrapper header (`thryve_ffi.h`) that adds
//! `extern "C"` guards for proper C++ linkage.
//!
//! # Usage
//!
//! To include the header in C/C++ code, add OUT_DIR to your include path:
//!
//! ```bash
//! # Using rustc directly
//! rustc ... -I $(cargo rustc --package thryve_ffi -- --print out-dir)
//!
//! # In CMake, this is done via:
//! # target_include_directories(my_target PRIVATE ${OUT_DIR})
//! ```
//!
//! # Generated Files
//!
//! - `thryve.h` — C-compatible header (generated by cbindgen)
//! - `thryve_ffi.h` — C++ wrapper header with `extern "C"` (generated by build.rs)
//!
//! # Including the header in C++ code
//!
//! In your C++ code, include the wrapper header instead of the raw header:
//!
//! ```cpp
//! // C++ code
//! #include "thryve_ffi.h"  // This includes extern "C" wrapper
//! ```
//!
//! In your C code, include the raw header directly:
//!
//! ```c
//! // C code
//! #include "thryve.h"
//! ```

fn main() {
    // Generate the C header using cbindgen
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR not set");
    let builder = cbindgen::Builder::new()
        .with_crate(&manifest_dir)
        .with_config(
            cbindgen::Config::from_file(std::path::Path::new(&manifest_dir).join("cbindgen.toml"))
                .unwrap_or_default(),
        );

    // Generate and write the main C header
    let header = builder
        .generate()
        .expect("cbindgen failed to generate header");
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR not set");
    let header_path = std::path::Path::new(&out_dir).join("thryve.h");
    header.write_to_file(&header_path);

    println!(
        "cargo:warning=Generated header at {}",
        header_path.display()
    );

    // Post-process: replace `const uint8_t*` with `const void*` in function pointer typedefs
    // cbindgen generates function pointers with `const uint8_t*` instead of the idiomatic `const void*`
    // For example: typedef void (*ThryvePluginCleanUp)(const uint8_t*);
    // Should be:    typedef void (*ThryvePluginCleanUp)(const void*);
    let mut header_content = std::fs::read_to_string(&header_path)
        .expect("Failed to read generated header for post-processing");
    header_content = header_content.replace(")(const uint8_t*", ")(const void*");
    std::fs::write(&header_path, &header_content).expect("Failed to write post-processed header");
    println!(
        "cargo:warning=Post-processed header: replaced const uint8_t* with const void* in function pointer typedefs"
    );

    // Create the C++ wrapper header with extern "C" guards
    // This header includes the raw C header within extern "C" so it works correctly in C++
    let wrapper_header = "#ifndef THRYVE_FFI_H\n\
         #define THRYVE_FFI_H\n\
         \n\
         #ifdef __cplusplus\n\
         extern \"C\" {\n\
         #endif\n\
         \n\
         #include \"thryve.h\"\n\
         \n\
         #ifdef __cplusplus\n\
         }\n\
         #endif\n\
         \n\
         #endif /* THRYVE_FFI_H */\n"
        .to_string();

    let wrapper_path = std::path::Path::new(&out_dir).join("thryve_ffi.h");
    std::fs::write(&wrapper_path, wrapper_header).expect("Failed to write wrapper header");

    // Also copy the headers to the OUT_DIR root for easier access
    let out_dir_path = std::path::Path::new(&out_dir);
    if let Some(file_name) = header_path.file_name() {
        let dest = out_dir_path.join(file_name);
        std::fs::copy(&header_path, &dest).ok();
    }
    if let Some(file_name) = wrapper_path.file_name() {
        let dest = out_dir_path.join(file_name);
        std::fs::copy(&wrapper_path, &dest).ok();
    }

    // Copy headers to a stable output directory (thryve_ffi/out/) for IDE support
    // This allows VS Code's C/C++ extension to find the headers without glob patterns
    // Use CARGO_MANIFEST_DIR to get the correct path regardless of working directory
    let out_dir_crate = std::path::Path::new(&manifest_dir).join("out");
    std::fs::create_dir_all(&out_dir_crate).ok();
    let stable_header_path = out_dir_crate.join("thryve.h");
    let stable_wrapper_path = out_dir_crate.join("thryve_ffi.h");
    std::fs::copy(&header_path, &stable_header_path).ok();
    std::fs::copy(&wrapper_path, &stable_wrapper_path).ok();
    println!(
        "cargo:warning=Headers copied to stable location: {}/",
        out_dir_crate.display()
    );

    // Re-run if cbindgen.toml, Cargo.toml, or lib.rs changes
    println!("cargo:rerun-if-changed=cbindgen.toml");
    println!("cargo:rerun-if-changed=Cargo.toml");
    println!("cargo:rerun-if-changed=src/lib.rs");
}
